#!/usr/bin/env python3
"""Gate-level simulation wrapper for a routed gdf_core netlist.

The place-and-route netlist (asic/pnr) has the SRAM and ROM pins as top-level
ports (expose -evert).  This script renames its top module to gdf_core_pnr and
writes a module gdf_core with the RTL interface that reconnects those ports
to the behavioral SRAM and ROM models of rtl/gdf_core.v, so that
tb/tb_gdf.cpp can drive the routed netlist unchanged.

Usage: gl_wrap.py <final.v> <outdir>
"""
import re
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
RTLDIR = Path(__file__).resolve().parents[2] / "rtl"
ROMS = {"gdf_rom_pcw": str(RTLDIR / "pcw_class.hex"), "gdf_rom_sel": str(RTLDIR / "pcw_sel.hex")}
out.mkdir(parents=True, exist_ok=True)
net = src.read_text()
net, n = re.subn(r"^module gdf_core\s*\(", "module gdf_core_pnr(", net, count=1, flags=re.M)
assert n == 1, "top module gdf_core not found"
(out / "gdf_core_pnr.v").write_text(net)

# port declarations of the (only) module of the netlist
ports = []
for m in re.finditer(r"^\s*(input|output)\s+(\[(\d+):(\d+)\]\s+)?(\\\S+|\w+)\s*;", net, re.M):
    d, msb, lsb, name = m.group(1), m.group(3), m.group(4), m.group(5)
    w = int(msb) - int(lsb) + 1 if msb is not None else 1
    ports.append((d, name.lstrip("\\"), w))
seen = set()
ports = [p for p in ports if not (p[1] in seen or seen.add(p[1]))]

rams = {}
core = []
for d, name, w in ports:
    mm = re.match(r"(.*\.(u_cb|u_ccb|u_lb\d|u_lut|u_ql|u_lc|u_pcr|u_sel))\.(\w+)$", name)
    if mm:
        rams.setdefault(mm.group(1), {})[mm.group(3)] = (d, w)
    else:
        core.append((d, name, w))

def sig(name):
    return "w_" + re.sub(r"[^A-Za-z0-9]", "_", name)

L = ["// generated by asic/pnr/gl_wrap.py: routed gdf_core + behavioral SRAMs",
     "module gdf_core ("]
L.append(",\n".join(f"  {d} wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{n}" for d, n, w in core))
L.append(");")
for inst, pins in sorted(rams.items()):
    for pin, (d, w) in sorted(pins.items()):
        L.append(f"  wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{sig(inst + '.' + pin)};")
conn = [f"    .{n}({n})" for _, n, _ in core]
for inst, pins in sorted(rams.items()):
    for pin in sorted(pins):
        conn.append(f"    .\\{inst}.{pin} ({sig(inst + '.' + pin)})")
L.append("  gdf_core_pnr u_pnr (\n" + ",\n".join(conn) + "\n  );")
for k, (inst, pins) in enumerate(sorted(rams.items())):
    s = lambda p: sig(inst + "." + p)
    if "q0" in pins:          # error table: 1 write/read + 1 read port
        L.append(f"  gdf_ram_lut u_ram{k} (.clk({s('clk')}), .we({s('we')}), .wa({s('wa')}), "
                 f".wd({s('wd')}), .ra0({s('ra0')}), .ra1({s('ra1')}), .q0({s('q0')}), .q1({s('q1')}));")
    elif "q" in pins:         # ROM: PC-Wiener class ROM or LR filter selector
        rom = "gdf_rom_pcw" if inst.endswith("u_pcr") else "gdf_rom_sel"
        hexf = ROMS[rom]
        L.append(f"  {rom} #(.FILE(\"{hexf}\")) u_rom{k} (.clk({s('clk')}), .a({s('a')}), "
                 f".q({s('q')}));")
    else:                     # simple dual-port buffer / table
        W, AW = pins["rq"][1], pins["ra"][1]
        L.append(f"  gdf_ram_sdp #(.W({W}), .D({1 << AW}), .AW({AW})) u_ram{k} (.clk({s('clk')}), "
                 f".re({s('re')}), .ra({s('ra')}), .rq({s('rq')}), .we({s('we')}), .wa({s('wa')}), "
                 f".wd({s('wd')}));")
L.append("endmodule")
(out / "gl_wrap.v").write_text("\n".join(L) + "\n")

# behavioral SRAM models from the RTL
rtl = (Path(__file__).resolve().parents[2] / "rtl" / "gdf_core.v").read_text()
mods = []
for name in ("gdf_ram_sdp", "gdf_ram_lut", "gdf_rom_pcw", "gdf_rom_sel"):
    a = rtl.index(f"module {name}")
    b = rtl.index("endmodule", a) + len("endmodule")
    mods.append(rtl[a:b])
(out / "gl_rams.v").write_text("`default_nettype wire\n" + "\n\n".join(mods) + "\n")
print(f"core ports {len(core)}, SRAMs {len(rams)}: {', '.join(sorted(rams))}")
